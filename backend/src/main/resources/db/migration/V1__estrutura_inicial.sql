-- Estrutura inicial do banco Porto Cabral (Firebird 5)

-- Comparações e ordenação de texto sem diferenciar maiúsculas/minúsculas
-- (mesmo comportamento do SQL Server usado anteriormente)
ALTER CHARACTER SET UTF8 SET DEFAULT COLLATION UNICODE_CI;

CREATE TABLE PESSOA (
    ID        INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOME      VARCHAR(255),
    CPF       VARCHAR(255),
    TELEFONE  VARCHAR(255),
    CONSTRAINT PK_PESSOA PRIMARY KEY (ID),
    -- CPF é opcional (NULL); o Firebird permite vários NULL em coluna UNIQUE
    CONSTRAINT UK_PESSOA_CPF UNIQUE (CPF)
);

CREATE TABLE USUARIO (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PESSOA_ID      INTEGER NOT NULL,
    USUARIO_LOGIN  VARCHAR(255) NOT NULL,
    EMAIL          VARCHAR(255) NOT NULL,
    SENHA          VARCHAR(255),
    PERFIL         VARCHAR(255) NOT NULL,
    DATA_CRIACAO   TIMESTAMP,
    CONSTRAINT PK_USUARIO PRIMARY KEY (ID),
    CONSTRAINT UK_USUARIO_PESSOA UNIQUE (PESSOA_ID),
    CONSTRAINT UK_USUARIO_LOGIN UNIQUE (USUARIO_LOGIN),
    CONSTRAINT UK_USUARIO_EMAIL UNIQUE (EMAIL),
    CONSTRAINT FK_USUARIO_PESSOA FOREIGN KEY (PESSOA_ID) REFERENCES PESSOA (ID)
);

CREATE TABLE CLIENTE (
    ID         BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    PESSOA_ID  INTEGER NOT NULL,
    OBS        VARCHAR(255),
    CONSTRAINT PK_CLIENTE PRIMARY KEY (ID),
    CONSTRAINT UK_CLIENTE_PESSOA UNIQUE (PESSOA_ID),
    CONSTRAINT FK_CLIENTE_PESSOA FOREIGN KEY (PESSOA_ID) REFERENCES PESSOA (ID)
);

CREATE TABLE CATEGORIA (
    ID    BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOME  VARCHAR(255),
    CONSTRAINT PK_CATEGORIA PRIMARY KEY (ID)
);

CREATE TABLE PRODUTO (
    ID            BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    NOME          VARCHAR(255),
    PRECO         NUMERIC(18,2),
    PRECO_CUSTO   NUMERIC(18,2),
    ESTOQUE       INTEGER,
    CATEGORIA_ID  BIGINT,
    CONSTRAINT PK_PRODUTO PRIMARY KEY (ID),
    CONSTRAINT FK_PRODUTO_CATEGORIA FOREIGN KEY (CATEGORIA_ID) REFERENCES CATEGORIA (ID)
);

CREATE TABLE VENDA (
    ID               BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    CLIENTE_ID       BIGINT NOT NULL,
    USUARIO_ID       BIGINT NOT NULL,
    DATA_VENDA       TIMESTAMP,
    FORMA_PAGAMENTO  VARCHAR(255),
    VALOR_PAGO       NUMERIC(18,2),
    CONSTRAINT PK_VENDA PRIMARY KEY (ID),
    CONSTRAINT FK_VENDA_CLIENTE FOREIGN KEY (CLIENTE_ID) REFERENCES CLIENTE (ID),
    CONSTRAINT FK_VENDA_USUARIO FOREIGN KEY (USUARIO_ID) REFERENCES USUARIO (ID)
);

CREATE TABLE VENDA_ITEM (
    ID              BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    VENDA_ID        BIGINT NOT NULL,
    PRODUTO_ID      BIGINT NOT NULL,
    QUANTIDADE      INTEGER,
    PRECO_UNITARIO  NUMERIC(18,2),
    CONSTRAINT PK_VENDA_ITEM PRIMARY KEY (ID),
    CONSTRAINT FK_VENDA_ITEM_VENDA FOREIGN KEY (VENDA_ID) REFERENCES VENDA (ID),
    CONSTRAINT FK_VENDA_ITEM_PRODUTO FOREIGN KEY (PRODUTO_ID) REFERENCES PRODUTO (ID)
);

CREATE TABLE AUDITORIA_LOG (
    ID             BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    USUARIO_ID     BIGINT,
    USUARIO_NOME   VARCHAR(255),
    TIPO_OPERACAO  VARCHAR(255),
    DESCRICAO      VARCHAR(500),
    DATA_HORA      TIMESTAMP,
    CONSTRAINT PK_AUDITORIA_LOG PRIMARY KEY (ID)
);
